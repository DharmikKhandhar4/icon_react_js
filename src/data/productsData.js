// Helper function to get category by slug
export function getCategoryBySlug(slug) {
  if (!slug) return foodCategories[0];
  const normalized = slug.toLowerCase().replace(/%20/g, '-').replace(/\s+/g, '-');
  return foodCategories.find(c => c.slug === normalized || c.slug === slug) || foodCategories[0];
}

// Helper function to get machines for a category
export function getMachinesByCategory(categorySlug) {
  const category = getCategoryBySlug(categorySlug);
  if (!category || !category.machines) {
    return Object.values(machinesCatalog).slice(0, 4);
  }
  return category.machines
    .map(slug => machinesCatalog[slug])
    .filter(Boolean);
}

// Helper function to get machine by slug
export function getMachineBySlug(machineSlug) {
  if (!machineSlug) return machinesCatalog["double-chamber-vacuum-packing-machine"];
  const normalized = machineSlug.toLowerCase().replace(/%20/g, '-').replace(/\s+/g, '-');
  return machinesCatalog[normalized] || machinesCatalog["double-chamber-vacuum-packing-machine"];
}

